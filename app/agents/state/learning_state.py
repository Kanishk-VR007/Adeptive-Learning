from typing import Any, Dict, List, Optional, Union
from typing_extensions import TypedDict
from pydantic import BaseModel, Field, field_validator


class EvaluationItem(BaseModel):
    is_correct: bool = Field(description="Whether the answer is conceptually correct")
    answer_type: str = Field(
        default="correct",
        description="Classification: correct, partially_correct, incorrect, ambiguous"
    )
    reasoning_summary: str = Field(
        default="",
        description="Concise, evidence-based reasoning summary without raw chain-of-thought"
    )
    confidence: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Model confidence score between 0.0 and 1.0"
    )


class MisconceptionItem(BaseModel):
    detected: bool = Field(default=False, description="Whether a conceptual misconception was identified")
    concept_id: Optional[Union[str, int]] = Field(default=None, description="Affected concept identifier")
    category: Optional[str] = Field(
        default="none",
        description=(
            "Error category: conceptual_misconception, calculation_error, "
            "incorrect_formula_application, incomplete_understanding, "
            "careless_mistake, incorrect_prerequisite_knowledge, unclear_response, none"
        )
    )
    description: Optional[str] = Field(default=None, description="Pedagogical description of the error")

    @field_validator("category", mode="before")
    @classmethod
    def normalize_category(cls, v: Any) -> str:
        if v is None:
            return "none"
        return str(v)



class CandidateQuestionItem(BaseModel):
    concept_id: Optional[Union[str, int]] = Field(default=None, description="Concept identifier for follow-up")
    difficulty: str = Field(default="medium", description="Calibrated difficulty: easy, medium, hard")
    question: str = Field(description="Question text")
    expected_answer: str = Field(description="Expected reference answer")
    evaluation_criteria: List[str] = Field(default_factory=list, description="Grading rubric points")


class DeepSeekAnalysisOutput(BaseModel):
    """
    Combined DeepSeek-R1 output schema combining answer evaluation,
    misconception detection, and calibrated follow-up question drafting in a single inference pass.
    """
    evaluation: EvaluationItem
    misconception: Optional[MisconceptionItem] = Field(
        default_factory=lambda: MisconceptionItem(detected=False, category="none", description=None)
    )
    candidate_question: Optional[CandidateQuestionItem] = None


class StudentFeedbackOutput(BaseModel):
    """
    Student-facing feedback structure generated by Llama 3.2.
    """
    feedback: str = Field(description="Warm, supportive pedagogical feedback")
    socratic_hint: Optional[str] = Field(default=None, description="Gentle hint guiding student without giving answer away")
    next_question: Optional[str] = Field(default=None, description="Calibrated follow-up probe or next question")
    adaptive_action: str = Field(default="TARGETED_PRACTICE", description="Pedagogical action decided deterministically")
    display_mastery: float = Field(default=0.20, ge=0.0, le=1.0, description="Deterministic mastery from BKT engine")


class AdaptiveActionType:
    CONCEPT_REMEDIATION = "CONCEPT_REMEDIATION"
    TARGETED_PRACTICE = "TARGETED_PRACTICE"
    ADVANCE_TO_NEXT_CONCEPT = "ADVANCE_TO_NEXT_CONCEPT"
    REVISION_RECOMMENDATION = "REVISION_RECOMMENDATION"
    CLARIFICATION_REQUIRED = "CLARIFICATION_REQUIRED"


class LearningState(TypedDict, total=False):
    """
    Typed centralized LangGraph state representing a complete adaptive learning turn.
    Maintains only necessary data across node transitions.
    """
    run_id: str
    session_id: Optional[int]
    student_id: int
    student_name: Optional[str]
    question_id: int
    concept_id: int
    student_answer: str

    # Context & candidate selection
    current_concept_id: int
    current_concept_name: Optional[str]
    candidate_next_concept_id: Optional[int]
    candidate_next_concept_name: Optional[str]
    current_mastery: Optional[float]
    relevant_learning_context: Optional[Dict[str, Any]]

    # Evaluation & Misconceptions (DeepSeek)
    validated_answer: Optional[Dict[str, Any]]
    evaluation_result: Optional[Dict[str, Any]]
    misconception_analysis: Optional[Dict[str, Any]]
    reasoning_summary: Optional[str]
    evaluation_confidence: Optional[float]
    is_uncertain_evaluation: bool
    clarification_prompt: Optional[str]
    generated_question: Optional[Dict[str, Any]]

    # BKT & Learner Modeling (Python)
    evidence_id: Optional[str]
    updated_mastery: Optional[float]
    posterior_mastery: Optional[float]

    # Adaptive Decision (Python)
    adaptive_action: Optional[str]
    adaptive_reasoning: Optional[str]
    validated_next_question: Optional[Dict[str, Any]]

    # Student Feedback (Llama)
    student_feedback: Optional[Dict[str, Any]]

    # Persistence & Telemetry
    response_id: Optional[int]
    execution_status: str
    error_code: Optional[str]
    error_message: Optional[str]
    node_execution_trace: List[str]
    metrics: Dict[str, float]

    # Spaced Repetition (FSRS)
    turn_type: Optional[str]  # "NORMAL_PRACTICE" or "SCHEDULED_REVISION"
    review_rating: Optional[int]  # 1: Again, 2: Hard, 3: Good, 4: Easy
    idempotency_key: Optional[str]
    fsrs_card_updated: Optional[Dict[str, Any]]
    fsrs_next_due_utc: Optional[str]
    fsrs_retrievability: Optional[float]

